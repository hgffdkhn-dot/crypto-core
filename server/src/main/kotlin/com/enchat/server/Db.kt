/**
 * 数据源与建表。
 *
 * DDL 说明：PostgreSQL 与 H2 的 DDL 分别维护（H2 仅用于集成测试与本地演示）。
 * 所有二进制字段以 Base64 字符串存储，避免 BYTEA / BINARY 的类型差异；代价是体积 +33%，
 * 对密钥（≤96B）与消息（≤8KB 明文）都可接受。
 */
object Db {

    private const val POSTGRES_SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid           BIGINT UNIQUE NOT NULL,
  username      VARCHAR(64) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  nickname      VARCHAR(64) NOT NULL DEFAULT '',
  avatar_url    VARCHAR(512) NOT NULL DEFAULT '',
  signature     VARCHAR(256) NOT NULL DEFAULT '',
  identity_ed   VARCHAR(64) NOT NULL DEFAULT '',
  identity_x    VARCHAR(64) NOT NULL DEFAULT '',
  created_at    BIGINT NOT NULL,
  status        INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash VARCHAR(64) PRIMARY KEY,
  user_id    BIGINT NOT NULL,
  device_id  VARCHAR(64) NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS signed_prekeys (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL,
  spk_id     INT NOT NULL,
  public_key VARCHAR(64) NOT NULL,
  signature  VARCHAR(128) NOT NULL,
  active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at BIGINT NOT NULL,
  UNIQUE (user_id, spk_id)
);
CREATE TABLE IF NOT EXISTS one_time_prekeys (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL,
  opk_id     INT NOT NULL,
  public_key VARCHAR(64) NOT NULL,
  consumed   BOOLEAN NOT NULL DEFAULT FALSE,
  created_at BIGINT NOT NULL,
  UNIQUE (user_id, opk_id)
);
CREATE TABLE IF NOT EXISTS friendships (
  user_id    BIGINT NOT NULL,
  friend_id  BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (user_id, friend_id)
);
CREATE TABLE IF NOT EXISTS friend_requests (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_user  BIGINT NOT NULL,
  to_user    BIGINT NOT NULL,
  message    VARCHAR(256) NOT NULL DEFAULT '',
  state      INT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  handled_at BIGINT
);
CREATE TABLE IF NOT EXISTS conversations (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type            INT NOT NULL,
  encryption_mode INT NOT NULL DEFAULT 1,
  owner_uid       BIGINT NOT NULL DEFAULT 0,
  group_id        VARCHAR(32) NOT NULL DEFAULT '',
  title           VARCHAR(128) NOT NULL DEFAULT '',
  avatar_url      VARCHAR(512) NOT NULL DEFAULT '',
  group_epoch     INT NOT NULL DEFAULT 1,
  created_at      BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS conversation_members (
  conversation_id BIGINT NOT NULL,
  user_id         BIGINT NOT NULL,
  role            INT NOT NULL DEFAULT 0,
  joined_at       BIGINT NOT NULL,
  left_at         BIGINT,
  PRIMARY KEY (conversation_id, user_id)
);
CREATE TABLE IF NOT EXISTS messages (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL,
  sender_id       BIGINT NOT NULL,
  kind            INT NOT NULL,
  plaintext       TEXT,
  ciphertext      TEXT,
  e2ee_session_id VARCHAR(64),
  e2ee_index      INT,
  group_epoch     INT,
  created_at      BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_messages_conv_id ON messages (conversation_id, id);
CREATE INDEX IF NOT EXISTS idx_messages_created ON messages (created_at);
CREATE INDEX IF NOT EXISTS idx_opk_lookup ON one_time_prekeys (user_id, consumed);
"""

    private const val H2_SCHEMA = POSTGRES_SCHEMA // H2 2.x 支持 IDENTITY 与本 DDL 语法

    fun create(config: Config): HikariDataSource {
        val hikari = HikariConfig().apply {
            jdbcUrl = config.jdbcUrl
            username = config.dbUser
            password = config.dbPassword
            maximumPoolSize = config.dbPoolSize
            isAutoCommit = true
            if (config.isH2) connectionInitSql = "SET MODE PostgreSQL; SET LOCK_TIMEOUT 10000"
        }
        val ds = HikariDataSource(hikari)
        migrate(ds)
        return ds
    }

    fun migrate(ds: DataSource) {
        val sql = if (isH2(ds)) H2_SCHEMA else POSTGRES_SCHEMA
        ds.connection.use { conn ->
            conn.createStatement().use { st ->
                sql.split(";").map { it.trim() }.filter { it.isNotBlank() }.forEach { stmt ->
                    st.execute(stmt)
                }
            }
        }
    }

    private fun isH2(ds: DataSource): Boolean =
        ds.connection.use { it.metaData.url.startsWith("jdbc:h2") }

    /** 在事务中执行；异常自动回滚并抛出。 */
    fun <T> inTx(ds: DataSource, block: (Connection) -> T): T {
        ds.connection.use { conn ->
            val old = conn.autoCommit
            conn.autoCommit = false
            return try {
                val r = block(conn)
                conn.commit()
                r
            } catch (t: Throwable) {
                runCatching { conn.rollback() }
                throw t
            } finally {
                runCatching { conn.autoCommit = old }
            }
        }
    }
}

// ---------------- JDBC 小工具 ----------------

fun Connection.query(sql: String, vararg args: Any?, block: (ResultSet) -> Unit) {
    prepareStatement(sql).use { ps ->
        args.forEachIndexed { i, a -> ps.setObject(i + 1, a) }
        ps.executeQuery().use { rs -> while (rs.next()) block(rs) }
    }
}

fun Connection.exec(sql: String, vararg args: Any?): Int {
    prepareStatement(sql).use { ps ->
        args.forEachIndexed { i, a -> ps.setObject(i + 1, a) }
        return ps.executeUpdate()
    }
}

/** 插入并返回自增 id（H2 / PostgreSQL 都支持 RETURN_GENERATED_KEYS 取回 identity 列）。 */
fun Connection.insert(sql: String, vararg args: Any?): Long {
    prepareStatement(sql, java.sql.Statement.RETURN_GENERATED_KEYS).use { ps ->
        args.forEachIndexed { i, a -> ps.setObject(i + 1, a) }
        ps.executeUpdate()
        ps.generatedKeys.use { rs ->
            return if (rs.next()) rs.getLong(1) else 0L
        }
    }
}

fun Connection.findOne(sql: String, vararg args: Any?): Map<String, Any?>? {
    var row: Map<String, Any?>? = null
    query(sql, *args) { rs ->
        val meta = rs.metaData
        val map = linkedMapOf<String, Any?>()
        for (i in 1..meta.columnCount) map[meta.getColumnLabel(i).lowercase()] = rs.getObject(i)
        row = map
    }
    return row
}

fun Connection.findLong(sql: String, vararg args: Any?): Long? =
    findOne(sql, *args)?.values?.firstOrNull()?.let { (it as? Number)?.toLong() }
